# MAE===============================
# 1. 定义数值与颜色
# ===============================
values <- c(0.0254, 0.0519, 0.0493, 0.0386)
colors <- c("#D62728", "#5A3E36", "#2F4858", "#B08D57")

# ===============================
# 2. PNG 输出
# ===============================
png(
  filename = "D:/MAE.png",
  width = 3000,
  height = 1200,
  res = 300,
  type = "cairo"
)

# ===============================
# 3. 字体与全局参数
# ===============================
windowsFonts(TNR = windowsFont("Times New Roman"))
par(
  family = "TNR",
  mar = c(4, 4, 1, 1),  # 图边距
  mgp = c(2, 0.1, 0),
  tck = 0,              # 全局刻度线由 axis 控制
  lwd = 2
)

# ===============================
# 4. 设置纵轴范围（上边加 4% 空白，下边保持 0）
# ===============================
y_base <- c(0, 0.05)
y_range <- diff(y_base)
y_pad_top <- 0.15 * y_range
ylim_pad <- c(y_base[1], y_base[2] + y_pad_top)

# ===============================
# 5. 绘制柱状图
# ===============================
par(xpd = FALSE)  # 不超出图区域
bar_centers <- barplot(
  height = values,
  col = colors,
  border = NA,
  ylim = ylim_pad,
  axes = FALSE,
  space = 0.5,
  width = 0.6
)

# ===============================
# 6. 添加纵轴刻度（6 个刻度，刻度线朝内）
# ===============================
y_ticks <- seq(y_base[1], y_base[2], length.out = 6)
# 使用 segments 绘制刻度线
x_left <- par("usr")[1]  # 左边界
tick_len <- 0.006 * diff(par("usr")[1:2])  # 刻度长度（相对于 x 轴）
for (yt in y_ticks) {
  segments(
    x0 = x_left + tick_len,  # 刻度线从左向右
    y0 = yt,
    x1 = x_left,              # 向左画到图内
    y1 = yt,
    lwd = 2.5
  )
}

# ===============================
# 7. 横轴不显示刻度
# ===============================
axis(1, labels = FALSE, tcl = 0, lwd = 0)

# ===============================
# 8. 加粗外框
# ===============================
box(lwd = 2.5)

# ===============================
# 9. 关闭设备
# ===============================
dev.off()




